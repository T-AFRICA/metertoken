/**
 * Writes supabase/schema.sql: every migration in one transaction, recorded in schema_migrations the
 * way migrate() records them, so the API skips them on its first start. Paste the file into the
 * Supabase SQL Editor on an empty project. Re-run after adding a migration.
 *
 *   npm run schema:supabase
 */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const migrationsDir = fileURLToPath(new URL('../migrations/', import.meta.url));
const outFile = fileURLToPath(new URL('../../../supabase/schema.sql', import.meta.url));

const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('.sql')).sort();
const parts = [
  '-- Tronic STS portal schema for Supabase (PostgreSQL). Generated by apps/api/scripts/supabase-schema.ts',
  '-- from apps/api/migrations; do not edit by hand. Run once, on an empty project, in the SQL Editor.',
  'BEGIN;',
  'CREATE TABLE IF NOT EXISTS schema_migrations (version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());',
];
for (const file of files) {
  const sql = (await readFile(migrationsDir + file, 'utf8')).trim();
  parts.push(`\n-- ${file}\n${sql}\nINSERT INTO schema_migrations(version) VALUES ('${file}');`);
}
parts.push('\nCOMMIT;\n');

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, parts.join('\n'));
console.log(`Wrote ${outFile} (${files.length} migrations)`);
